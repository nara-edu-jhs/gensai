// An approximate UI suggestion only; never claim this is a point-in-polygon lookup.
export function nearbyPrefecture(point) {
  if(!point || !Number.isFinite(point.latitude) || !Number.isFinite(point.longitude))return '';
  const cosine=Math.cos(point.latitude*Math.PI/180);
  return prefectures.reduce((best,p)=>{
    const distance=(p[3]-point.latitude)**2+((p[4]-point.longitude)*cosine)**2;
    return distance<best.distance?{name:p[0],distance}:best;
  },{name:'',distance:Infinity}).name;
}
export function officialSearch(prefecture,mode){
  if(!prefectures.some(p=>p[0]===prefecture))return null;
  const query=`${prefecture} ${mode==='bus'?'バス会社':'鉄道会社'} 運行情報 公式`;
  return 'https://www.google.com/search?'+new URLSearchParams({q:query});
}
export function initTransit(getJourney){
  const button=document.createElement('button');button.type='button';button.id='transit-trigger';button.textContent=ui('電車・バスの運行情報');button.setAttribute('aria-haspopup','dialog');button.setAttribute('aria-controls','transit-dialog');
  document.querySelector('#gsi-map').append(button);
  const dialog=document.createElement('dialog');dialog.id='transit-dialog';dialog.setAttribute('aria-labelledby','transit-title');
  function element(tag,text,className){const el=document.createElement(tag);if(text)el.textContent=ui(text);if(className)el.className=className;return el;}
  const title=element('h2','全国の運行情報を確認');title.id='transit-title';
  const close=element('button','閉じる');close.type='button';close.className='transit-close';close.addEventListener('click',()=>dialog.close());
  const heading=element('div',null,'transit-heading');heading.append(title,close);dialog.append(heading);
  function link(text,url){const a=element('a',text);a.href=url;a.target='_blank';a.rel='noopener noreferrer';return a;}
  const nationwide=element('div',null,'transit-links');nationwide.append(link('全国の鉄道（ジョルダン） ↗','https://www.jorudan.co.jp/unk/index.html'),link('全国のバス案内（NAVITIME） ↗','https://www.navitime.co.jp/bustransit/'));dialog.append(nationwide,element('p','交通案内サイトが別のタブで開きます。対象外の路線もあるため、最終確認は各交通会社の公式情報で行ってください。'));
  dialog.append(element('h3','地域から公式情報を探す'));
  const label=element('label','都道府県');label.htmlFor='transit-prefecture';const select=element('select');select.id='transit-prefecture';
  function updateOptions(){const selected=select.value;select.replaceChildren();const all=element('option','全国から選ぶ');all.value='';select.append(all);prefectures.forEach(([name,en,kana])=>{const option=element('option');option.value=name;option.textContent=document.documentElement.lang==='ja'?`${name}（${kana}）`:`${en} / ${name}`;select.append(option);});select.value=selected;}
  const shortcuts=element('div',null,'transit-shortcuts');const origin=element('button','出発地の近く（目安）'),destination=element('button','目的地の近く（目安）');origin.type=destination.type='button';shortcuts.append(origin,destination);
  const searches=element('div',null,'transit-links');const rail=link('鉄道会社の公式情報を検索 ↗','#'),bus=link('バス会社の公式情報を検索 ↗','#');searches.append(rail,bus);searches.hidden=true;
  function updateLinks(){searches.hidden=!select.value;if(select.value){rail.href=officialSearch(select.value,'rail');bus.href=officialSearch(select.value,'bus');}}
  select.addEventListener('change',updateLinks);
  origin.addEventListener('click',()=>{select.value=nearbyPrefecture(getJourney().origin);updateLinks();});destination.addEventListener('click',()=>{select.value=nearbyPrefecture(getJourney().destination);updateLinks();});
  dialog.append(label,select,shortcuts,element('small','近い県庁所在地を目安に選びます。県境・離島では選び直してください。'),searches,element('p','検索結果から会社名・公式サイトを確認してください。掲載がないことは通常運行を意味しません。'),element('p','運行情報の確認には通信が必要です。オフライン保存に最新の運行状況は含まれません。','transit-note'));
  document.body.append(dialog);
  button.addEventListener('click',()=>{const journey=getJourney();updateOptions();origin.hidden=!journey.origin;destination.hidden=!journey.destination;if(!select.value)select.value=nearbyPrefecture(journey.origin);updateLinks();dialog.showModal();});
  dialog.addEventListener('click',event=>{if(event.target===dialog){const box=dialog.getBoundingClientRect();if(event.clientX<box.left||event.clientX>box.right||event.clientY<box.top||event.clientY>box.bottom)dialog.close();}});
  dialog.addEventListener('close',()=>button.focus({preventScroll:true}));
}
